//! MCP server over stdio (rmcp 3.10) — tools map 1:1 onto engine commands.
//!
//! Verified against the vendored crate source (`rmcp-3.10.0/src/handler/server/
//! router/tool.rs` + `rmcp-macros-3.10.0`): the macro pattern is
//! `#[tool_router] impl Server { #[tool(name = .., description = ..)] fn .. }`
//! plus `#[tool_handler(router = self.tool_router)] impl ServerHandler`, and the
//! service is started with `ServiceExt::serve(rmcp::transport::stdio())` on a Tokio
//! runtime. Tool arguments arrive as `Parameters<T>` with `T: Deserialize +
//! JsonSchema`; results are `Json<serde_json::Value>` (structured content, and
//! `serde_json::Value: JsonSchema` gives the output schema for free).
//!
//! `doc_export` is a first-class tool because it is the one command whose params
//! deserve a typed surface (`path`, `format`, `quality`); every other command goes
//! through `command_run {id, params}` and therefore needs no MCP code when the
//! registry grows.

use std::sync::{Arc, Mutex};

use rmcp::handler::server::router::tool::ToolRouter;
use rmcp::handler::server::wrapper::{Json, Parameters};
use rmcp::model::{ServerCapabilities, ServerConfig};
use rmcp::{ServerHandler, ServiceExt, tool, tool_handler, tool_router};
use schemars::JsonSchema;
use serde::Deserialize;
use serde_json::{Value, json};
use snagcraft_engine::Session;

use crate::{AutomationError, commands_json, dispatch};

/// `command_run` arguments.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct RunArgs {
    /// Engine command id, exactly as listed by `command_list` (e.g. `doc.new`).
    pub id: String,
    /// The command's params object; omit for commands that take `{}`.
    #[serde(default)]
    pub params: Option<Value>,
}

/// `doc_export` arguments.
#[derive(Debug, Deserialize, JsonSchema)]
pub struct ExportArgs {
    /// Destination file path.
    pub path: String,
    /// `png` (default), `jpeg` or `webp`.
    #[serde(default)]
    pub format: Option<String>,
    /// 1..=100, only meaningful for `jpeg`.
    #[serde(default)]
    pub quality: Option<u8>,
}

/// The MCP server: one engine session behind a mutex, tools generated by rmcp.
pub struct McpServer {
    session: Arc<Mutex<Session>>,
    tool_router: ToolRouter<Self>,
}

impl McpServer {
    /// Build a server bound to an engine session.
    pub fn new(session: Arc<Mutex<Session>>) -> Self {
        Self {
            session,
            tool_router: Self::tool_router(),
        }
    }

    fn call(&self, id: &str, params: Value) -> Result<Json<Value>, String> {
        dispatch(&self.session, id, params).map(Json)
    }
}

#[tool_handler(
    router = self.tool_router,
    name = "snagcraft",
    version = "0.1.0",
    instructions = "SnagCraft screenshot editor. Start with command_list to see the engine commands, then command_run. ui.screenshot is available through command_run{\"id\":\"doc.export\"} or doc_export for files.",
)]
impl ServerHandler for McpServer {
    fn get_info(&self) -> ServerConfig {
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build()).with_instructions(
            "SnagCraft automation: registry-driven screenshot editing. \
             Use command_list for the full command surface.",
        )
    }
}

#[tool_router]
impl McpServer {
    /// List every engine command with its id, label and params documentation.
    #[tool(
        name = "command_list",
        description = "List all engine commands (id, label, params doc)."
    )]
    fn command_list(&self) -> Json<Value> {
        Json(commands_json())
    }

    /// Run any engine command by id with its params object.
    #[tool(
        name = "command_run",
        description = "Run an engine command by id, e.g. {\"id\":\"doc.new\",\"params\":{\"w\":640,\"h\":480}}."
    )]
    fn command_run(&self, args: Parameters<RunArgs>) -> Result<Json<Value>, String> {
        let Parameters(RunArgs { id, params }) = args;
        self.call(&id, params.unwrap_or_else(|| json!({})))
    }

    /// Session state: open document size, object count, undo/redo availability.
    #[tool(
        name = "session_info",
        description = "Current session state: has_doc, size, objects, can_undo/can_redo."
    )]
    fn session_info(&self) -> Result<Json<Value>, String> {
        self.call("session.info", json!({}))
    }

    /// Full document description: size, next object id, every annotation object.
    #[tool(
        name = "doc_inspect",
        description = "Inspect the open document: size, next_id and all objects."
    )]
    fn doc_inspect(&self) -> Result<Json<Value>, String> {
        self.call("doc.inspect", json!({}))
    }

    /// Export the composited document to a file.
    #[tool(
        name = "doc_export",
        description = "Export the composited document to a file: {path, format?: png|jpeg|webp, quality?: 1-100}."
    )]
    fn doc_export(&self, args: Parameters<ExportArgs>) -> Result<Json<Value>, String> {
        let Parameters(ExportArgs {
            path,
            format,
            quality,
        }) = args;
        let mut params = json!({"path": path});
        if let Some(format) = format {
            params["format"] = Value::String(format);
        }
        if let Some(quality) = quality {
            params["quality"] = Value::from(quality);
        }
        self.call("doc.export", params)
    }
}

/// Serve MCP over process stdio. Blocks until the peer closes stdin.
///
/// Builds its own multi-thread Tokio runtime: the caller is a plain `fn` per the
/// L6 contract, and rmcp needs an async context for the stdio transport.
pub fn serve_mcp_stdio(session: Arc<Mutex<Session>>) -> Result<(), AutomationError> {
    let server = McpServer::new(session);
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(2)
        .enable_all()
        .build()
        .map_err(|e| AutomationError::Mcp(format!("tokio runtime: {e}")))?;
    runtime.block_on(async move {
        let running = server
            .serve(rmcp::transport::stdio())
            .await
            .map_err(|e| AutomationError::Mcp(format!("mcp initialize: {e}")))?;
        tracing::info!("mcp stdio server initialized");
        running
            .waiting()
            .await
            .map_err(|e| AutomationError::Mcp(format!("mcp join: {e}")))?;
        tracing::info!("mcp stdio server stopped");
        Ok(())
    })
}

#[cfg(test)]
mod tests {
    //! Offline protocol smoke test: a real rmcp service over an in-memory duplex
    //! stream, driven with raw newline-delimited JSON-RPC frames. No subprocess,
    //! no network, no clock dependency.

    use super::*;
    use std::sync::Mutex as StdMutex;
    use tokio::io::{AsyncBufReadExt, AsyncRead, AsyncWrite, AsyncWriteExt, BufReader};

    fn session_with_doc() -> Arc<StdMutex<Session>> {
        let mut session = Session::new();
        session
            .dispatch("doc.new", json!({"w": 64, "h": 48}))
            .expect("doc.new");
        Arc::new(StdMutex::new(session))
    }

    async fn send(w: &mut (impl AsyncWrite + Unpin), frame: Value) {
        let mut line = serde_json::to_vec(&frame).expect("serialize");
        line.push(b'\n');
        w.write_all(&line).await.expect("write frame");
        w.flush().await.expect("flush");
    }

    async fn recv(lines: &mut tokio::io::Lines<BufReader<impl AsyncRead + Unpin>>) -> Value {
        let line = lines
            .next_line()
            .await
            .expect("read frame")
            .expect("frame present");
        serde_json::from_str(&line).expect("parse frame")
    }

    async fn server_task(
        io: tokio::io::DuplexStream,
    ) -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
        let running = McpServer::new(session_with_doc()).serve(io).await?;
        running.waiting().await?;
        Ok::<(), Box<dyn std::error::Error + Send + Sync>>(())
    }

    #[tokio::test(flavor = "current_thread")]
    async fn initialize_tools_list_and_tool_call() {
        let (server_io, client_io) = tokio::io::duplex(1 << 16);
        let server = tokio::spawn(server_task(server_io));
        let (read_half, mut write_half) = tokio::io::split(client_io);
        let mut lines = BufReader::new(read_half).lines();

        send(
            &mut write_half,
            json!({
                "jsonrpc": "2.0", "id": 1, "method": "initialize",
                "params": {
                    "protocolVersion": rmcp::model::ProtocolVersion::LATEST_WITH_INITIALIZE.to_string(),
                    "capabilities": {},
                    "clientInfo": {"name": "snagcraft-test", "version": "0"}
                }
            }),
        )
        .await;
        let init = recv(&mut lines).await;
        assert_eq!(init["id"], 1);
        assert!(
            init["result"]["capabilities"]["tools"].is_object(),
            "server must advertise the tools capability: {init}"
        );

        send(
            &mut write_half,
            json!({"jsonrpc": "2.0", "method": "notifications/initialized"}),
        )
        .await;

        send(
            &mut write_half,
            json!({"jsonrpc": "2.0", "id": 2, "method": "tools/list"}),
        )
        .await;
        let list = recv(&mut lines).await;
        let names: Vec<&str> = list["result"]["tools"]
            .as_array()
            .expect("tools array")
            .iter()
            .filter_map(|t| t["name"].as_str())
            .collect();
        for expected in [
            "command_list",
            "command_run",
            "session_info",
            "doc_inspect",
            "doc_export",
        ] {
            assert!(
                names.contains(&expected),
                "missing tool {expected}: {names:?}"
            );
        }
        assert_eq!(names.len(), 5, "unexpected extra tools: {names:?}");

        send(
            &mut write_half,
            json!({
                "jsonrpc": "2.0", "id": 3, "method": "tools/call",
                "params": {"name": "command_run",
                           "arguments": {"id": "doc.new", "params": {"w": 32, "h": 24}}}
            }),
        )
        .await;
        let call = recv(&mut lines).await;
        assert_eq!(call["id"], 3);
        assert_ne!(call["result"]["isError"], true, "tool call failed: {call}");

        send(
            &mut write_half,
            json!({
                "jsonrpc": "2.0", "id": 4, "method": "tools/call",
                "params": {"name": "session_info", "arguments": {}}
            }),
        )
        .await;
        let info = recv(&mut lines).await;
        assert_eq!(info["id"], 4);
        assert_ne!(info["result"]["isError"], true, "tool call failed: {info}");

        // Close both halves of the duplex so the server sees EOF on stdin.
        drop(lines);
        drop(write_half);
        let joined = tokio::time::timeout(std::time::Duration::from_secs(5), server)
            .await
            .expect("server should stop when the client closes");
        assert!(
            joined.expect("server task").is_ok(),
            "server exited with an error"
        );
    }

    /// `serve_mcp_stdio` is a thin runtime wrapper; the router is the single
    /// source of tool truth, so assert it lists exactly the five tools.
    #[test]
    fn router_lists_exactly_the_five_tools() {
        let mut session = Session::new();
        session
            .dispatch("doc.new", json!({"w": 8, "h": 8}))
            .expect("doc.new");
        let server = McpServer::new(Arc::new(StdMutex::new(session)));
        let mut names: Vec<String> = server
            .tool_router
            .list_all()
            .iter()
            .map(|t| t.name.to_string())
            .collect();
        names.sort();
        assert_eq!(
            names,
            vec![
                "command_list",
                "command_run",
                "doc_export",
                "doc_inspect",
                "session_info"
            ]
        );
    }
}
